def test_chunked_batch_sync_simulation(running_server):
  """Phase 3 Test: Verify chunked batch syncing by simulating 150 entries in multiple chunks.

  Ensures desktop daemon accepts chunked bursts (e.g. 100 + 50) and persists them idempotently.
  """
  server, base_url, ledger_path = running_server

  # Generate 150 unique valid entries
  all_entries = []
  for i in range(150):
    entry = {
        "receipt_id": f"rec-bulk-{i:03d}",
        "receipt_date": "2026-03-01",
        "merchant": f"Store {i % 5}",
        "item": f"Bulk Item {i}",
        "brand": "Generic",
        "category": "Food and beverages",
        "quantity": 1.0,
        "pack_size": 1.0,
        "unit": "unit",
        "unit_price": 10.0 + (i % 20),
        "currency": "MXN",
        "discount": 0.0,
        "fee": 0.0,
        "tax": 0.0,
        "deposit": 0.0,
        "paid_total": -(10.0 + (i % 20)),
        "event_type": "recurring",
        "store_tier": "A",
        "store_rating": 5.0,
        "brand_tier": "A",
        "brand_rating": 5.0,
        "product_tier": "A",
        "product_rating": 5.0,
        "availability": "in_stock",
        "notes": f"Batch item {i}",
        "account": "default:checking",
        "recorded_at": "2026-03-01T10:00:00Z",
    }
    # Compute deterministic entry_id
    entry["entry_id"] = compute_entry_id(
        receipt_id=entry["receipt_id"],
        item=entry["item"],
        paid_total=entry["paid_total"],
        receipt_date=entry["receipt_date"],
    )
    all_entries.append(entry)

  # Chunk into batches of size 100
  batch_size = 100
  chunks = [all_entries[i:i + batch_size] for i in range(0, len(all_entries), batch_size)]
  assert len(chunks) == 2  # 100 and 50

  imported_total = 0
  for idx, chunk in enumerate(chunks):
    payload = {"entries": chunk, "force": False, "account": "default:checking"}
    status, data = make_http_post(f"{base_url}/api/v1/sync/push", payload)
    assert status == 200, f"Chunk {idx} failed with {data}"
    assert data["status"] == "success"
    assert data["imported"] == len(chunk)
    imported_total += data["imported"]

  assert imported_total == 150

  # Verify daemon reports 150 entries in health check
  h_status, h_data = make_http_get(f"{base_url}/api/v1/health")
  assert h_status == 200
  assert h_data["entry_count"] == 150

  # Re-push all 150 entries: should be cleanly skipped
  for idx, chunk in enumerate(chunks):
    payload = {"entries": chunk, "force": False, "account": "default:checking"}
    status, data = make_http_post(f"{base_url}/api/v1/sync/push", payload)
    assert status == 200
    assert data["imported"] == 0
    assert data["skipped"] == len(chunk)


def test_server_mdns_registration_and_cleanup_helpers():
  """Phase 3 Test: Verify mDNS/Zeroconf advertisement helper gracefully handles

  both missing zeroconf and mocked/present zeroconf registration and unregistration.
  """
  import sys
  from unittest.mock import MagicMock, patch

  # 1. When zeroconf is NOT installed (ImportError)
  with patch.dict(sys.modules, {"zeroconf": None}):
    reg = register_zeroconf_service(port=8000)
    assert reg is None
    # unregister with None should safely no-op
    unregister_zeroconf_service(None)

  # 2. When zeroconf is present, test registration & teardown lifecycle
  mock_zeroconf_mod = MagicMock()
  mock_zc_instance = MagicMock()
  mock_info_instance = MagicMock()
  mock_zeroconf_mod.Zeroconf.return_value = mock_zc_instance
  mock_zeroconf_mod.ServiceInfo.return_value = mock_info_instance
  mock_zeroconf_mod.IPVersion.V4Only = "V4Only"

  with patch.dict(sys.modules, {"zeroconf": mock_zeroconf_mod}):
    reg = register_zeroconf_service(
        port=8443,
        service_type="_peit-sync._tcp.local.",
        properties={"version": "0.1.0", "schema": "25"},
    )
    assert reg is not None
    zc, info = reg
    assert zc is mock_zc_instance
    assert info is mock_info_instance
    mock_zc_instance.register_service.assert_called_once_with(mock_info_instance)

    # Test clean unregistration
    unregister_zeroconf_service(reg)
    mock_zc_instance.unregister_service.assert_called_once_with(mock_info_instance)
    mock_zc_instance.close.assert_called_once()


