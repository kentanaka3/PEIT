def make_http_post(url: str, data: dict[str, Any]) -> tuple[int, dict[str, Any]]:
  """Helper to POST JSON payload to test server."""
  body = json.dumps(data).encode("utf-8")
  req = urllib.request.Request(
      url,
      data=body,
      headers={"Content-Type": "application/json; charset=utf-8"},
      method="POST",
  )
  try:
    with urllib.request.urlopen(req) as resp:
      return resp.status, json.loads(resp.read().decode("utf-8"))
  except urllib.error.HTTPError as err:
    return err.code, json.loads(err.read().decode("utf-8"))


def make_http_get(url: str) -> tuple[int, dict[str, Any]]:
  """Helper to GET JSON payload from test server."""
  req = urllib.request.Request(url, headers={"Accept": "application/json"})
  with urllib.request.urlopen(req) as resp:
    return resp.status, json.loads(resp.read().decode("utf-8"))


