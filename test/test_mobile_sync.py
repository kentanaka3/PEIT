def test_mobile_deterministic_sha256_hash_parity():
  """Verify that Dart's computeEntryId algorithm produces the identical SHA-256

  as Python's peit.ledger.compute_entry_id for edge-case numbers and strings.
  """
  test_cases = [
      ("rec-001", "milk 1 l", -2.50, "2026-01-15"),
      ("rec-002", "pan blanco 500g", -49.0, "2026-02-01"),
      ("rec-003", "manzana kg", -32.555555, "2026-03-10"),
      ("rec-004", "salary payment", 15000.0, "2026-04-01"),
  ]

  for receipt_id, item, paid_total, receipt_date in test_cases:
    # Python ledger calculation
    py_hash = compute_entry_id(
        receipt_id=receipt_id,
        item=item,
        paid_total=paid_total,
        receipt_date=receipt_date,
    )

    # Dart algorithm implementation replicated exactly:
    # final normAmount = paidTotal.toStringAsFixed(6);
    # final raw = '${receiptId.trim()}|${item.trim()}|$normAmount|${receiptDate.trim()}';
    # final digest = sha256.convert(utf8.encode(raw));
    dart_norm_amount = f"{float(paid_total):.6f}"
    dart_raw = f"{receipt_id.strip()}|{item.strip()}|{dart_norm_amount}|{receipt_date.strip()}"
    dart_hash = hashlib.sha256(dart_raw.encode("utf-8")).hexdigest()

    assert py_hash == dart_hash, (
        f"Hash mismatch for {receipt_id}: py={py_hash} vs dart={dart_hash}"
    )


